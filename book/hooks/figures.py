"""MkDocs hook: give every figure a dark-theme twin.

`![alt](…/figures/NAME.svg)` becomes the light image plus `NAME-dark.svg`, using
Material's `#only-light` / `#only-dark` switches. Figures are generated by
scripts/make_figures.py.
"""

import re

FIG = re.compile(r"!\[([^\]]*)\]\(([^)\s]*/figures/[\w-]+)\.svg\)")


def on_page_markdown(markdown, **kwargs):
    return FIG.sub(r"![\1](\2.svg#only-light)![\1](\2-dark.svg#only-dark)", markdown)
